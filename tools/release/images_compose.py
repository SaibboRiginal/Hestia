#!/usr/bin/env python3
"""Ready-made images of a release: keep docker-compose.images.yml in step with docker-compose.global.yml.

Usage:
  python tools/release/images_compose.py           # (re)write docker-compose.images.yml
  python tools/release/images_compose.py --check   # exit 1 when the file is out of date (governance gate)
  python tools/release/images_compose.py --list    # JSON [{"service", "dockerfile"}] for the images workflow

Every service of docker-compose.global.yml that has a `build:` gets, in the override, an image of the single GHCR
package `ghcr.io/saibboriginal/hestia` tagged `<service>-<version>` (one package = one visibility switch).
`docker compose -f docker-compose.global.yml -f docker-compose.images.yml pull` then downloads a release instead
of building it; without the override (up-all.bat, Forge) everything still builds locally as before.
Standard library only: the installer may run it in a bare python container. SPEC: docs/work/2026-10-30-setup-un-click
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
COMPOSE = ROOT / "docker-compose.global.yml"
OVERRIDE = ROOT / "docker-compose.images.yml"
SERVICE_RE = re.compile(r"^  ([a-z0-9_-]+):\s*$")
DOCKERFILE_RE = re.compile(r"^\s+dockerfile:\s*(\S+)")

HEADER = """\
# GENERATED by tools/release/images_compose.py from docker-compose.global.yml — do not edit by hand.
# Ready-made images of a Hestia release (built by .github/workflows/images.yml on every tag vX.Y.Z):
#   HESTIA_VERSION=1.2.0 docker compose -f docker-compose.global.yml -f docker-compose.images.yml pull
# HESTIA_VERSION empty = latest release. HESTIA_IMAGES = another registry/package (forks).
# A service whose image is missing is built locally from its `build:` as usual.
services:
"""


def built_services() -> list[dict[str, str]]:
    """Services with a `build:` section, in compose order: [{"service", "dockerfile"}]."""
    out: list[dict[str, str]] = []
    current = ""
    in_services = False
    for line in COMPOSE.read_text(encoding="utf-8-sig").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line.startswith(" "):
            in_services = line.startswith("services:")
            continue
        if not in_services:
            continue
        match = SERVICE_RE.match(line)
        if match:
            current = match.group(1)
            continue
        match = DOCKERFILE_RE.match(line)
        if match and current:
            out.append({"service": current, "dockerfile": match.group(1)})
            current = ""
    return out


def render() -> str:
    lines = [HEADER]
    for item in built_services():
        lines.append(f"  {item['service']}:\n")
        lines.append(f"    image: ${{HESTIA_IMAGES:-ghcr.io/saibboriginal/hestia}}:{item['service']}-"
                     "${HESTIA_VERSION:-latest}\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    if "--list" in argv:
        print(json.dumps(built_services()))
        return 0
    text = render()
    if "--check" in argv:
        if not OVERRIDE.exists() or OVERRIDE.read_text(encoding="utf-8") != text:
            print("docker-compose.images.yml is out of date: run python tools/release/images_compose.py")
            return 1
        print(f"event=images_compose_ok services={len(built_services())}")
        return 0
    OVERRIDE.write_text(text, encoding="utf-8", newline="\n")
    print(f"event=images_compose_written services={len(built_services())}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
